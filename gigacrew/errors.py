"""Общие исключения gigacrew, не зависящие от остальных модулей."""

from __future__ import annotations


class ToolError(Exception):
    """Ожидаемая ошибка инструмента (возвращается модели, не роняет агента)."""


class SandboxError(ToolError):
    """Попытка выйти за пределы песочницы проекта.

    Наследует ToolError: агент обрабатывает её как обычную ошибку инструмента
    (сообщает модели), а не как сбой программы.
    """
